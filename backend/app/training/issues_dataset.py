def get_all_100_issues() -> list[dict[str, Any]]:
    """Return the structured 100 real-time issues formatted for Astrix closed-loop training."""
    dataset: list[dict[str, Any]] = []
    for idx, raw in enumerate(RAW_ISSUES, start=1):
        issue_id = f"ISSUE-{idx:03d}"
        situation = {
            "severity": "CRITICAL" if raw["final_score"] >= 0.75 else ("WARNING" if raw["final_score"] >= 0.55 else "WATCH"),
            "ml_score": raw["ml_score"],
            "final_score": raw["final_score"],
            "persistence_seconds": raw["persistence"],
            "deviating_parameters": raw["deviating"],
            "context_factors": {
                "ml_anomaly_score": raw["ml_score"],
                "context_deviation": round(max(0.1, raw["final_score"] - 0.25), 3),
                "subsystem_correlation": 0.15 if raw["is_spoof"] else 0.75,
                "historical_similarity": 0.85,
                "persistence": round(min(1.0, raw["persistence"] / 300.0), 3),
                "mission_impact": 0.20 if raw["is_spoof"] else round(raw["final_score"] * 0.9, 3),
            },
        }
        decision = {
            "diagnosis": {
                "subsystem": raw["subsystem"],
                "component": raw["component"],
                "failure_mode": raw["failure_mode"],
                "probable_cause": raw["probable_cause"],
                "confidence": 0.95 if not raw["is_spoof"] else 0.88,
            },
            "risk": {
                "severity": situation["severity"],
                "mission_impact": "LOW (Transient/Instrumentation Glitch)" if raw["is_spoof"] else "MODERATE/HIGH (Physical Subsystem Impact)",
                "time_to_impact_minutes": 120.0 if raw["is_spoof"] else round(max(5.0, (1.0 - raw["final_score"]) * 100.0), 1),
            },
            "recovery": {
                "action_id": raw["action_id"],
                "risk_level": raw["risk_level"],
                "rationale": raw["rationale"],
            },
            "safety_status": "PASS",
        }
        problem_solving = {
            "is_sensor_spoof": raw["is_spoof"],
            "model_problem": "Sensor Glitch / Distribution Shift" if raw["is_spoof"] else "True Physical Fault",
            "resolution": raw["resolution"],
        }
        dataset.append({
            "id": issue_id,
            "raw_id": raw["id"],
            "title": raw["title"],
            "subsystem": raw["subsystem"],
            "component": raw["component"],
            "mode": raw["mode"],
            "situation": situation,
            "decision": decision,
            "problem_solving": problem_solving,
            "labels": {
                "subsystem": raw["subsystem"],
                "failure_mode": raw["failure_mode"],
                "action_id": raw["action_id"],
                "reasoner": "SMALL_LLM",
                "safety_status": "PASS",
            },
        })
    return dataset
